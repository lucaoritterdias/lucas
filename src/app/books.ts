/**
 * The books on the desk and the shelf, as they sit in the photos Lucas sent.
 * Spines are drawn from these: `color` is the spine, `ink` the title, `accent` the author line.
 */

export type Shelf = "mind" | "software" | "business" | "society";

export type Book = {
  title: string;
  /** the title of the original, for the English page */
  en: string;
  /** left out where the spine doesn't show it */
  author?: string;
  publisher: string;
  shelf: Shelf;
  /** "100 minutos para entender" */
  series?: boolean;
  color: string;
  ink: string;
  accent?: string;
  /** spine thickness in rem */
  thick: number;
  /** length of the book, as a share of the stack's width */
  length: number;
  face: "serif" | "sans" | "slab";
};

